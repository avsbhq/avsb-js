/** A flag as the platform knows it. */
export interface RegistryFlag {
  key: string
  status: string
  stale?: boolean
}

export interface ExtinctKey {
  key: string
  /** Why it is reported: gone entirely, or present but archived. */
  reason: 'unknown' | 'archived'
  references: FlagReference[]
}

export interface UnreferencedFlag {
  key: string
  status: string
  stale: boolean
}

export interface FindRefsReport {
  /** Keys the code asks for that the platform cannot serve. */
  extinct: ExtinctKey[]
  /** Flags the platform has that no scanned file mentions. */
  unreferenced: UnreferencedFlag[]
  /** Flags found in the code and live on the platform. */
  matchedKeys: string[]
  filesScanned: number
}

const ARCHIVED = 'ARCHIVED'

export function buildReport(
  registry: readonly RegistryFlag[],
  references: readonly FlagReference[],
  filesScanned: number,
): FindRefsReport {
  const byKey = new Map(registry.map((f) => [f.key, f]))
  const referenced = new Map<string, FlagReference[]>()

  for (const ref of references) {
    const bucket = referenced.get(ref.key)
    if (bucket) bucket.push(ref)
    else referenced.set(ref.key, [ref])
  }

  const extinct: ExtinctKey[] = []
  const matchedKeys: string[] = []

  for (const [key, refs] of referenced) {
    const flag = byKey.get(key)
    if (!flag) {
      extinct.push({ key, reason: 'unknown', references: refs })
      continue
    }
    if (flag.status === ARCHIVED) {
      extinct.push({ key, reason: 'archived', references: refs })
      continue
    }
    matchedKeys.push(key)
  }

  const unreferenced: UnreferencedFlag[] = registry
    .filter((f) => f.status !== ARCHIVED && !referenced.has(f.key))
    .map((f) => ({ key: f.key, status: f.status, stale: f.stale === true }))

  return {
    extinct: extinct.sort(byKeyName),
    unreferenced: unreferenced.sort(byKeyName),
    matchedKeys: matchedKeys.sort(),
    filesScanned,
  }
}

function byKeyName(a: { key: string }, b: { key: string }): number {
  return compareCodeUnits(a.key, b.key)
}
