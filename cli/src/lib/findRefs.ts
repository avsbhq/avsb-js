/** One place a flag key appears. */
export interface FlagReference {
  key: string
  /** Posix path relative to the scan root. */
  file: string
  /** 1-based. */
  line: number
  /** `getter` came from a recognised call; `literal` from a bare quoted key. */
  via: 'getter' | 'literal'
}

/** Files that carry this marker are generated by codegen and never scanned. */
export const GENERATED_MARKER = 'AUTO-GENERATED by @avsbhq/cli codegen'

export function isGeneratedFile(contents: string): boolean {
  // Only the head is inspected: the marker is on line 1, and a file that
  // mentions it in the middle is talking about codegen, not produced by it.
  return contents.slice(0, 400).includes(GENERATED_MARKER)
}

/**
 * `getBoolFlag('checkout-v2', false)` and friends: the call name, optional
 * generic arguments, then the argument list up to the key.
 *
 * Written as one expression per getter at scan time rather than one giant
 * alternation so a match reports which name it saw.
 */
function getterPattern(name: string, argIndex: number): RegExp {
  // Arguments before the key: anything that is not a closing paren, ending in a
  // comma. Good enough for `evaluateFlagServer(datafile, ctx, 'key', null)` and
  // deliberately gives up on a nested call in an earlier argument.
  const preceding = argIndex === 0 ? '' : `(?:[^()'"\`]*,){${argIndex}}\\s*`
  return new RegExp(
    `\\b${escapeRegExp(name)}\\s*(?:<[^<>()]*>\\s*)?\\(\\s*${preceding}(['"\`])([^'"\`\\n]+)\\1`,
    'g',
  )
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/**
 * Every flag key this file references.
 *
 * Two passes with different jobs. The getter pass finds keys we can name even
 * when the platform has never heard of them, which is what makes the extinct
 * report possible. The literal pass asks "does this exact key appear anywhere",
 * which is what stops a flag read through a config map or an HTML attribute
 * from being reported as dead code.
 */
export function scanFileForReferences(
  contents: string,
  file: string,
  knownKeys: ReadonlySet<string>,
): FlagReference[] {
  if (isGeneratedFile(contents)) return []

  const found: FlagReference[] = []
  const lineStarts = buildLineStarts(contents)
  const seen = new Set<string>()

  for (const [name, argIndex] of FLAG_GETTERS) {
    if (!contents.includes(name)) continue
    const pattern = getterPattern(name, argIndex)
    let match = pattern.exec(contents)
    while (match !== null) {
      const key = match[2]
      const line = lineAt(lineStarts, match.index)
      record(found, seen, { key, file, line, via: 'getter' })
      match = pattern.exec(contents)
    }
  }

  for (const key of knownKeys) {
    for (const quote of ['"', "'", '`']) {
      const needle = `${quote}${key}${quote}`
      let at = contents.indexOf(needle)
      while (at !== -1) {
        record(found, seen, { key, file, line: lineAt(lineStarts, at), via: 'literal' })
        at = contents.indexOf(needle, at + needle.length)
      }
    }
  }

  return found
}

function record(into: FlagReference[], seen: Set<string>, ref: FlagReference): void {
  // One finding per key per line: a getter match and a literal match on the
  // same line are the same reference seen twice.
  const fingerprint = `${ref.key}:${ref.line}`
  if (seen.has(fingerprint)) return
  seen.add(fingerprint)
  into.push(ref)
}

function buildLineStarts(contents: string): number[] {
  const starts = [0]
  for (let i = 0; i < contents.length; i += 1) {
    if (contents[i] === '\n') starts.push(i + 1)
  }
  return starts
}

function lineAt(lineStarts: readonly number[], offset: number): number {
  let low = 0
  let high = lineStarts.length - 1
  while (low < high) {
    const mid = Math.ceil((low + high) / 2)
    if (lineStarts[mid] <= offset) low = mid
    else high = mid - 1
  }
  return low + 1
}

