/**
 * What `avsb codegen` writes: the TypeScript file that turns a project's live
 * flags into types.
 *
 * Pure on purpose. Everything here is "datafile in, text out", so the exact
 * bytes are asserted in tests and `--check` can regenerate in memory and
 * compare without touching the network or the filesystem.
 *
 * The emitted file has two halves:
 *
 *   1. Named exports (`FlagKey`, `FlagValues`, `ContextSchema`) you import and
 *      use directly.
 *   2. A `declare global` block that augments `AvsbFlags`, the empty interface
 *      `@avsbhq/core` declares. That block is what makes `getBoolFlag`,
 *      `useFlag`, `avsbBoolFlagSignal` and every sibling accept this project's
 *      keys and reject a typo. Delete the block (or pass `--no-augment`) and
 *      every getter goes back to plain `string`: the contract is opt-in and
 *      nothing breaks without it.
 *
 * The global block is deliberately NOT `declare module '@avsbhq/core'`: eight
 * packages share one table, a consumer installs only one of them, and
 * augmenting a package you did not install directly fails under pnpm's strict
 * layout and Yarn PnP. The reasoning is written out in full in
 * packages/avsb-core/src/flagKeys.ts.
 */

import { inferJsonType } from './jsonTypeInference.js'
import { compareCodeUnits } from './compareKeys.js'

// ---------------------------------------------------------------------------
// Datafile shape — duck-typed locally so this command does not depend on the
// @avsbhq/core runtime package. The canonical wire types live there
// (FlagDatafile, FlagDatafileEntry, RegisteredAttribute). Every field beyond
// the four the emitter needs is optional: an older datafile simply omits it.
// ---------------------------------------------------------------------------

export interface DatafileVariation {
  id?: string
  key?: string
  value: unknown
}

export interface DatafileFlag {
  key: string
  type: 'boolean' | 'string' | 'number' | 'json'
  variations: DatafileVariation[]
  /** Whether this flag serves rules in the environment the datafile is for. */
  enabled?: boolean
  /** Which variation answers when no rule matches. */
  defaultVariationId?: string
}

export interface RegisteredAttribute {
  key: string
  type: string
  contextKind?: string
}

export interface CodegenDatafile {
  flags: DatafileFlag[]
  contextKinds?: string[]
  registeredAttributes?: RegisteredAttribute[] | string[]
  /**
   * When the environment was last published. Null (or absent) for one that has
   * never been published, which the header writes as `publishedAt=unknown`.
   * The CLI datafile route serves the stored publish time, never the request
   * time, so the same platform state always generates the same bytes.
   */
  publishedAt?: string | null
  environmentKey?: string
}

export interface CodegenContext {
  projectId: string
  env: string
  /**
   * False writes the file without the `declare global` block, for the one case
   * it cannot serve: two AvsB projects in a single TypeScript program, whose
   * two tables would merge into one contradictory global.
   */
  augment?: boolean
}

export const GENERATED_HEADER = '// AUTO-GENERATED by @avsbhq/cli codegen. Do not edit by hand.'

/** The whole generated file, ending in a newline. */
export function emitTypes(datafile: CodegenDatafile, ctx: CodegenContext): string {
  const lines: string[] = []
  lines.push(GENERATED_HEADER)
  lines.push(
    `// Source: project=${ctx.projectId} env=${ctx.env} publishedAt=${datafile.publishedAt ?? 'unknown'}`,
  )
  lines.push('')

  lines.push(emitFlagKeyUnion(datafile.flags))
  lines.push('')
  lines.push(emitFlagValues(datafile.flags))
  lines.push('')
  lines.push(emitContextSchema(datafile))
  lines.push('')

  if (ctx.augment !== false) {
    lines.push(emitAugmentation(datafile.flags))
    lines.push('')
  }

  return lines.join('\n')
}

function emitFlagKeyUnion(flags: DatafileFlag[]): string {
  if (flags.length === 0) return 'export type FlagKey = never'
  const sorted = [...flags].map((f) => f.key).sort()
  const body = sorted.map((k) => `  | ${quote(k)}`).join('\n')
  return `export type FlagKey =\n${body}`
}

function emitFlagValues(flags: DatafileFlag[]): string {
  if (flags.length === 0) {
    return 'export interface FlagValues {\n  [key: string]: never\n}'
  }
  const props = sortedFlags(flags)
    .map((f) => `  ${quote(f.key)}: ${tsTypeForFlag(f)}`)
    .join('\n')
  return `export interface FlagValues {\n${props}\n}`
}

/**
 * The `declare global` block.
 *
 * It restates the key/type table rather than writing `interface AvsbFlags
 * extends FlagValues {}` for one reason that matters: with no flags,
 * `FlagValues` carries an index signature (`[key: string]: never`), so
 * inheriting it would make `keyof AvsbFlags` equal `string` and quietly break
 * the "no table means plain strings" fallback. A restated table is also the
 * block a human can read and understand on its own.
 */
export function emitAugmentation(flags: DatafileFlag[]): string {
  const lines: string[] = []
  lines.push('// Teaches every typed getter in @avsbhq/browser and the framework adapters')
  lines.push('// which keys this project has. Remove this block and they accept any string.')
  lines.push('declare global {')

  if (flags.length === 0) {
    lines.push('  // No flags are published in this environment yet, so keys stay `string`.')
    lines.push(
      '  // eslint-disable-next-line @typescript-eslint/no-empty-object-type -- nothing to declare yet',
    )
    lines.push('  interface AvsbFlags {}')
  } else {
    lines.push('  interface AvsbFlags {')
    for (const flag of sortedFlags(flags)) {
      lines.push(`    ${quote(flag.key)}: ${tsTypeForFlag(flag)}`)
    }
    lines.push('  }')
  }

  lines.push('}')
  return lines.join('\n')
}

function sortedFlags(flags: DatafileFlag[]): DatafileFlag[] {
  return [...flags].sort((a, b) => compareCodeUnits(a.key, b.key))
}

/** The TypeScript type of one flag's value. Shared by both emitted tables. */
export function tsTypeForFlag(flag: DatafileFlag): string {
  switch (flag.type) {
    case 'boolean':
      return 'boolean'
    case 'number':
      return 'number'
    case 'json':
      return inferJsonType(flag.variations.map((v) => v.value))
    case 'string': {
      const allStringLiterals = flag.variations.every((v) => typeof v.value === 'string')
      if (!allStringLiterals || flag.variations.length === 0) return 'string'
      const literals = Array.from(new Set(flag.variations.map((v) => v.value as string))).sort()
      return literals.map((l) => quote(l)).join(' | ')
    }
    default:
      // The datafile is duck-typed here, so a flag type added to the platform
      // later arrives as a string this switch does not know. Falling through
      // would emit the literal text `undefined`, which parses as a valid type
      // and fails silently; `unknown` makes the consumer narrow instead.
      return 'unknown'
  }
}

function emitContextSchema(datafile: CodegenDatafile): string {
  const kinds = (datafile.contextKinds ?? ['user']).slice().sort()
  if (kinds.length === 0) {
    return 'export interface ContextSchema {\n  user: { key: string }\n}'
  }

  const attrs = normaliseRegisteredAttributes(datafile.registeredAttributes)

  const lines: string[] = ['export interface ContextSchema {']
  for (const kind of kinds) {
    const kindAttrs = attrs.filter((a) => (a.contextKind ?? 'user') === kind)
    const props: string[] = ['key: string']
    for (const a of kindAttrs.slice().sort((x, y) => compareCodeUnits(x.key, y.key))) {
      props.push(`${quote(a.key)}: ${tsTypeForAttribute(a.type)}`)
    }
    lines.push(`  ${quote(kind)}: { ${props.join('; ')} }`)
  }
  lines.push('}')
  return lines.join('\n')
}

export function normaliseRegisteredAttributes(
  ra: CodegenDatafile['registeredAttributes'],
): RegisteredAttribute[] {
  if (!ra) return []
  if (ra.length === 0) return []
  if (typeof ra[0] === 'string') {
    return (ra as string[]).map((k) => ({ key: k, type: 'string' }))
  }
  return ra as RegisteredAttribute[]
}

function tsTypeForAttribute(type: string): string {
  switch (type) {
    case 'string':
      return 'string'
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'json':
      return 'unknown'
    default:
      return 'string'
  }
}

function quote(s: string): string {
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}
