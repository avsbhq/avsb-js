import { describe, expect, it } from 'vitest'
import {
  describeDrift,
  describeDriftSummary,
  diffArtifact,
  diffArtifacts,
  type CodegenArtifact,
} from './codegenCheck.js'

const path = '/repo/src/generated/flags.ts'

function artifact(expected: string, actual: string | null): CodegenArtifact {
  return { path, expected, actual }
}

describe('diffArtifact', () => {
  it('reports nothing when the file matches byte for byte', () => {
    expect(diffArtifact(artifact('a\nb\n', 'a\nb\n'))).toBeNull()
  })

  it('reports a missing file as missing, with the line count it would write', () => {
    const drift = diffArtifact(artifact('a\nb\nc\n', null))
    expect(drift?.reason).toBe('missing')
    expect(drift?.line).toBeNull()
    expect(drift?.expectedLineCount).toBe(4)
    expect(drift?.actualLineCount).toBeNull()
  })

  it('names the first differing line, 1-based, with both sides', () => {
    const drift = diffArtifact(artifact("a\n'x': boolean\nc", "a\n'x': string\nc"))
    expect(drift?.reason).toBe('different')
    expect(drift?.line).toBe(2)
    expect(drift?.expectedLine).toBe("'x': boolean")
    expect(drift?.actualLine).toBe("'x': string")
  })

  it('treats a shorter file on disk as ending early rather than crashing', () => {
    const drift = diffArtifact(artifact('a\nb\nc', 'a\nb'))
    expect(drift?.line).toBe(3)
    expect(drift?.expectedLine).toBe('c')
    expect(drift?.actualLine).toBeNull()
  })

  it('ignores CRLF line endings so a Windows checkout does not fail the gate', () => {
    expect(diffArtifact(artifact('a\nb\n', 'a\r\nb\r\n'))).toBeNull()
  })

  it('still catches a real content change in a CRLF file', () => {
    const drift = diffArtifact(artifact('a\nb\n', 'a\r\nB\r\n'))
    expect(drift?.line).toBe(2)
  })
})

describe('diffArtifacts', () => {
  it('returns only the artifacts that drifted, in order', () => {
    const drifts = diffArtifacts([
      { path: '/a', expected: 'same', actual: 'same' },
      { path: '/b', expected: 'new', actual: null },
      { path: '/c', expected: 'x', actual: 'y' },
    ])
    expect(drifts.map((d) => d.path)).toEqual(['/b', '/c'])
    expect(drifts.map((d) => d.reason)).toEqual(['missing', 'different'])
  })
})

describe('describeDrift', () => {
  it('tells a missing file to run the same command without --check', () => {
    const drift = diffArtifact(artifact('a\nb', null))
    const lines = describeDrift(drift!)
    expect(lines[0]).toContain('has not been generated yet')
    expect(lines[1]).toContain('without --check')
  })

  it('shows the generated and on-disk lines side by side', () => {
    const drift = diffArtifact(artifact('a\nb', 'a\nB'))
    const lines = describeDrift(drift!)
    expect(lines[0]).toContain('line 2')
    expect(lines[1]).toBe('  generated: b')
    expect(lines[2]).toBe('  on disk:   B')
  })

  it('says "end of file" rather than printing nothing for a truncated side', () => {
    const drift = diffArtifact(artifact('a\nb', 'a'))
    expect(describeDrift(drift!)[2]).toBe('  on disk:   (end of file)')
  })

  it('truncates a very long line so the difference stays readable', () => {
    const long = `x${'y'.repeat(400)}`
    const drift = diffArtifact(artifact(long, 'x'))
    const generated = describeDrift(drift!)[1]
    expect(generated.length).toBeLessThan(160)
    expect(generated.endsWith('…')).toBe(true)
  })

  it('reports differing line counts when the files are different lengths', () => {
    const drift = diffArtifact(artifact('a\nb\nc', 'x'))
    expect(describeDrift(drift!).some((l) => l.includes('3 generated lines, 1 on disk'))).toBe(true)
  })
})

describe('describeDriftSummary', () => {
  it('says everything is current when nothing drifted', () => {
    expect(describeDriftSummary([])).toBe('Generated files are up to date.')
  })

  it('agrees with itself on singular and plural', () => {
    const one = diffArtifact(artifact('a', null))!
    expect(describeDriftSummary([one])).toBe('1 generated file is out of date.')
    expect(describeDriftSummary([one, one])).toBe('2 generated files are out of date.')
  })
})

describe('the publish stamp is not drift (QA N4-5)', () => {
  const header = (stamp: string) =>
    `// AUTO-GENERATED by @avsbhq/cli codegen. Do not edit by hand.\n// Source: project=42 env=production publishedAt=${stamp}\n\nexport type FlagKey =\n  | 'checkout_v2'\n`

  it('reports a file that differs only in publishedAt as up to date', () => {
    expect(diffArtifact(artifact(header('2026-10-02T09:00:00.000Z'), header('2026-09-30T08:15:00.000Z')))).toBeNull()
  })

  it('ignores the manifest stamp too, including a never-published null', () => {
    const manifest = (stamp: string) => `{\n  "environments": [\n    {\n      "key": "production",\n      "publishedAt": ${stamp}\n    }\n  ]\n}\n`

    expect(diffArtifact(artifact(manifest('"2026-10-02T09:00:00.000Z"'), manifest('null')))).toBeNull()
  })

  it('still reports a changed flag, on the line it changed, with the real text', () => {
    const drift = diffArtifact(
      artifact(header('2026-10-02T09:00:00.000Z'), header('2026-09-30T08:15:00.000Z').replace('checkout_v2', 'checkout_v1')),
    )

    expect(drift?.line).toBe(5)
    expect(drift?.expectedLine).toBe("  | 'checkout_v2'")
    expect(drift?.actualLine).toBe("  | 'checkout_v1'")
  })
})
