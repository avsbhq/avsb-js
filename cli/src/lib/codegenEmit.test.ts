import { describe, expect, it } from 'vitest'
import {
  emitAugmentation,
  emitTypes,
  tsTypeForFlag,
  type CodegenDatafile,
  type DatafileFlag,
} from './codegenEmit.js'

const ctx = { projectId: '42', env: 'production' }

function emit(df: Partial<CodegenDatafile>): string {
  return emitTypes({ flags: [], ...df } as CodegenDatafile, ctx)
}

describe('emitTypes — header', () => {
  it('emits the AUTO-GENERATED header with project and env', () => {
    const out = emit({ flags: [], publishedAt: '2026-05-29T00:00:00Z' })
    expect(out).toContain('// AUTO-GENERATED by @avsbhq/cli codegen')
    expect(out).toContain('project=42')
    expect(out).toContain('env=production')
    expect(out).toContain('publishedAt=2026-05-29T00:00:00Z')
  })

  it('falls back to publishedAt=unknown when datafile omits the field', () => {
    expect(emit({ flags: [] })).toContain('publishedAt=unknown')
  })
})

describe('emitTypes — FlagKey union', () => {
  it('emits FlagKey = never for an empty datafile', () => {
    expect(emit({ flags: [] })).toContain('export type FlagKey = never')
  })

  it('emits a sorted union for multiple flags', () => {
    const out = emit({
      flags: [
        { key: 'zeta', type: 'boolean', variations: [{ value: true }] },
        { key: 'alpha', type: 'boolean', variations: [{ value: false }] },
      ],
    })
    const alphaPos = out.indexOf("| 'alpha'")
    const zetaPos = out.indexOf("| 'zeta'")
    expect(alphaPos).toBeGreaterThan(-1)
    expect(zetaPos).toBeGreaterThan(alphaPos)
  })
})

describe('emitTypes — FlagValues typing per flag type', () => {
  it('emits `boolean` for boolean flags', () => {
    const out = emit({
      flags: [
        { key: 'feature-x', type: 'boolean', variations: [{ value: true }, { value: false }] },
      ],
    })
    expect(out).toContain("'feature-x': boolean")
  })

  it('emits a deduplicated string-literal union when all variations are strings', () => {
    const out = emit({
      flags: [
        {
          key: 'hero-copy',
          type: 'string',
          variations: [{ value: 'control' }, { value: 'variant-a' }, { value: 'control' }],
        },
      ],
    })
    expect(out).toContain("'hero-copy': 'control' | 'variant-a'")
  })

  it('emits `string` when variations include a non-string value', () => {
    const out = emit({
      flags: [{ key: 'mixed', type: 'string', variations: [{ value: 'control' }, { value: 42 }] }],
    })
    expect(out).toContain("'mixed': string")
  })

  it('emits `number` for number flags', () => {
    const out = emit({
      flags: [{ key: 'discount-pct', type: 'number', variations: [{ value: 10 }, { value: 20 }] }],
    })
    expect(out).toContain("'discount-pct': number")
  })

  it('emits `string` for a string flag with zero variations', () => {
    expect(emit({ flags: [{ key: 'empty', type: 'string', variations: [] }] })).toContain(
      "'empty': string",
    )
  })
})

describe('tsTypeForFlag — JSON flags carry their inferred shape', () => {
  it('infers the object shape shared by every variation', () => {
    const flag: DatafileFlag = {
      key: 'theme',
      type: 'json',
      variations: [{ value: { primary: '#fff', radius: 4 } }, { value: { primary: '#000', radius: 8 } }],
    }
    expect(tsTypeForFlag(flag)).toBe('{ primary: string; radius: number }')
  })

  it('marks a field optional when only some variations carry it', () => {
    const flag: DatafileFlag = {
      key: 'tiers',
      type: 'json',
      variations: [{ value: { tiers: 3 } }, { value: { tiers: 5, perks: ['fast'] } }],
    }
    expect(tsTypeForFlag(flag)).toBe('{ perks?: string[]; tiers: number }')
  })

  it('falls back to unknown when there is nothing to infer from', () => {
    expect(tsTypeForFlag({ key: 'blank', type: 'json', variations: [] })).toBe('unknown')
  })

  it('emits the inferred type into the generated file, not `unknown`', () => {
    const out = emit({
      flags: [{ key: 'theme', type: 'json', variations: [{ value: { primary: '#fff' } }] }],
    })
    expect(out).toContain("'theme': { primary: string }")
    expect(out).not.toContain("'theme': unknown")
  })
})

describe('emitTypes — ContextSchema', () => {
  it('emits a minimal `user` schema when contextKinds is absent', () => {
    const out = emit({ flags: [] })
    expect(out).toContain('export interface ContextSchema {')
    expect(out).toContain("'user': { key: string }")
  })

  it('emits each declared contextKind in alphabetical order', () => {
    const out = emit({ flags: [], contextKinds: ['user', 'organization'] })
    const orgPos = out.indexOf("'organization'")
    const userPos = out.indexOf("'user'")
    expect(orgPos).toBeGreaterThan(-1)
    expect(userPos).toBeGreaterThan(orgPos)
  })

  it('types registeredAttributes by their declared type', () => {
    const out = emit({
      flags: [],
      contextKinds: ['user'],
      registeredAttributes: [
        { key: 'plan', type: 'string', contextKind: 'user' },
        { key: 'age', type: 'number', contextKind: 'user' },
        { key: 'isPaid', type: 'boolean', contextKind: 'user' },
        { key: 'prefs', type: 'json', contextKind: 'user' },
      ],
    })
    expect(out).toContain("'plan': string")
    expect(out).toContain("'age': number")
    expect(out).toContain("'isPaid': boolean")
    expect(out).toContain("'prefs': unknown")
  })

  it('attributes default to the `user` kind when contextKind is omitted', () => {
    const out = emit({
      flags: [],
      contextKinds: ['user', 'organization'],
      registeredAttributes: [{ key: 'plan', type: 'string' }],
    })
    const userBlock = out.slice(out.indexOf("'user': {"))
    expect(userBlock).toContain("'plan': string")
    const orgBlock = out.slice(out.indexOf("'organization': {"), out.indexOf("'user': {"))
    expect(orgBlock).not.toContain("'plan'")
  })

  it('accepts legacy string[] registeredAttributes (typed as string by default)', () => {
    const out = emit({
      flags: [],
      contextKinds: ['user'],
      registeredAttributes: ['tier', 'segment'],
    })
    expect(out).toContain("'tier': string")
    expect(out).toContain("'segment': string")
  })
})

describe('emitAugmentation — the AvsbFlags block', () => {
  it('emits the exact global augmentation for a project with flags', () => {
    const flags: DatafileFlag[] = [
      { key: 'hero-copy', type: 'string', variations: [{ value: 'control' }, { value: 'variant-a' }] },
      { key: 'checkout-v2', type: 'boolean', variations: [{ value: true }, { value: false }] },
    ]

    expect(emitAugmentation(flags)).toBe(
      [
        '// Teaches every typed getter in @avsbhq/browser and the framework adapters',
        '// which keys this project has. Remove this block and they accept any string.',
        'declare global {',
        '  interface AvsbFlags {',
        "    'checkout-v2': boolean",
        "    'hero-copy': 'control' | 'variant-a'",
        '  }',
        '}',
      ].join('\n'),
    )
  })

  it('emits an empty interface, not an index signature, when no flags exist', () => {
    const out = emitAugmentation([])
    expect(out).toContain('interface AvsbFlags {}')
    // An index signature here would make keyof AvsbFlags `string` and silently
    // kill the "no table means plain strings" fallback in @avsbhq/core.
    expect(out).not.toContain('[key: string]')
    expect(out).toContain('eslint-disable-next-line')
  })

  it('types a JSON flag in the augmentation exactly as in FlagValues', () => {
    const flags: DatafileFlag[] = [
      { key: 'theme', type: 'json', variations: [{ value: { primary: '#fff' } }] },
    ]
    expect(emitAugmentation(flags)).toContain("    'theme': { primary: string }")
  })

  it('escapes a quote inside a flag key so the block still parses', () => {
    const flags: DatafileFlag[] = [
      { key: "it's-odd", type: 'boolean', variations: [{ value: true }] },
    ]
    expect(emitAugmentation(flags)).toContain("    'it\\'s-odd': boolean")
  })
})

describe('emitTypes — augmentation wiring', () => {
  it('includes the declare global block by default', () => {
    const out = emit({
      flags: [{ key: 'checkout-v2', type: 'boolean', variations: [{ value: true }] }],
    })
    expect(out).toContain('declare global {')
    expect(out).toContain('interface AvsbFlags {')
  })

  it('omits the block when augment is false, keeping the named exports', () => {
    const out = emitTypes(
      { flags: [{ key: 'checkout-v2', type: 'boolean', variations: [{ value: true }] }] },
      { ...ctx, augment: false },
    )
    expect(out).not.toContain('declare global')
    expect(out).toContain('export type FlagKey =')
    expect(out).toContain('export interface FlagValues {')
  })

  it('is byte-stable across runs and across flag ordering', () => {
    const a = emit({
      flags: [
        { key: 'b-flag', type: 'boolean', variations: [{ value: true }] },
        { key: 'a-flag', type: 'number', variations: [{ value: 1 }] },
      ],
    })
    const b = emit({
      flags: [
        { key: 'a-flag', type: 'number', variations: [{ value: 1 }] },
        { key: 'b-flag', type: 'boolean', variations: [{ value: true }] },
      ],
    })
    expect(a).toBe(b)
  })
})

describe('emitTypes — deterministic output (QA N4-5)', () => {
  const datafile: CodegenDatafile = {
    publishedAt: '2026-09-30T08:15:00.000Z',
    flags: [
      { key: 'zeta', type: 'string', variations: [{ value: 'b' }, { value: 'a' }] },
      { key: 'alpha', type: 'boolean', variations: [{ value: true }, { value: false }] },
    ],
    registeredAttributes: [{ key: 'plan', type: 'string' }],
  }

  it('writes byte-identical output for the same datafile, every time', () => {
    expect(emitTypes(datafile, ctx)).toBe(emitTypes(structuredClone(datafile), ctx))
  })

  it('does not depend on the order the platform lists the flags in', () => {
    const reversed = { ...datafile, flags: [...datafile.flags].reverse() }

    expect(emitTypes(reversed, ctx)).toBe(emitTypes(datafile, ctx))
  })

  it('writes publishedAt=unknown for an environment that was never published (null)', () => {
    expect(emit({ publishedAt: null }).split('\n')[1]).toBe(
      '// Source: project=42 env=production publishedAt=unknown',
    )
  })
})
